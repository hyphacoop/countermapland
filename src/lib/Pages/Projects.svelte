<p>
  Reflex Urbanism is an urban practice studio transforming the culture of cities. Reflex Urbanism understand, from experience, the complex nature of contemporary urban life. The same places
marginalized people flock to marginalize us in return. Rather than call to centre the
marginalized, Reflex uplifts power among the margins. Through relational research, planning,
training, and action, Reflex addresses urban issues by and for equity-deserving communities.
</p>

<p>
  Reflex is based in the Haudenosaunee and Anishinaabe territories known as Tkaronto, Ogimaa
Mikana, and Toronto. As such, we are beholden to the Dish With One Spoon and Two Row
Wampum covenants. Our studio serves those for whom these covenants also apply.
