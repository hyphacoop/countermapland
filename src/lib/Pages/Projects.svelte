<p>
  <strong> Stride Gallery & Tsuut'ina Nation Youth Program </strong>
</p>

<p>
  <i>
  “countermap.land was the conceptual jumping off point for this project. We
  worked with artists Bruno Canadien, Sachin Sudra and Tsuut'ina Knowledge
  Keeper Kendall Jacob to share the idea of mapping and experiencing spaces
  around so-called Calgary through Indigenous perspectives. We visited Fort
  Calgary, a historically significant spot for Treaty 7 people, at the
  confluence of Bow and Elbow River. Fort Calgary and surrounding landmarks like
  the Deanne House, which is now a fine dining restaurant, are centered around
  colonial-settler narratives, but there are also historical events, stories,
  and myths of Blackfoot, Tsuut'ina and Stoney Nakoda peoples in that area. We
  walked around the spaces and listened to Kendall's stories and teachings, and
  also asked the youth to map the space via their own sensory experiences. The
  staff was tasked to update countermap.land as the Elders and Knoweldge Keepers
  preferred to deliver programs on site, without a technology component.”
</i>
</p>

<p>
  Stride Gallery is an artist-run centre located on the traditional territories of Tsuut’ina, Niitsitapi,
and Iyarhe Nakoda in Treaty 7, in a city colonially known as Calgary. Tsuut’ina Nation Youth Program (TNYP) operates from Tsuut’tina Nation, facilitating the Nation’s junior powwow and various youth programs. Since 2018, our organizations have been collaborating on a youth art program named Gumisistiy, which means “to persevere” or “to keep going” in Tsuut’ina.
</p>

<p>
  Gumisistiy Youth Program tackles the question of access to art and reciprocal relationship
building between First Nations and art institutions. Our two organizations are building a lasting
relationship that fosters artistic growth and agency for the youth. Acknowledging the historically
racist and unsafe arts institutions, Gumisistiy connects Tsuut’ina youth and different art spaces
in the city through various art workshops. Artists lead programs to introduce their own practices
that are constantly expanding and reshaping what it means to be an Indigenous artist in this
moment. These artists offer potential role models and pathways to finding a creative voice and
self-expression for the youth. The program introduces ceremony to the colonial spaces, with the
intention of making Tsuut’ina ways of being porously present in Treaty 7 areas.

</p>

<p>
  Learn more at: <a href="https://www.stride.ab.ca/">https://www.stride.ab.ca/</a> and <a href="https://www.instagram.com/tsuutina.youth.program">https://www.instagram.com/tsuutina.youth.program</a> 

</p>

